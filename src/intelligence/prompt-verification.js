/**
 * Builds the mode-keyed contract invocations over a fresh fixture set.
 * @returns {Record<string, [string, Record<string, any>]>}
 */
export function make_contract_cases() {
  const { entities, npc, snapshot, history } = create_contract_fixtures();

  return {
    director: ["director", { round: 1, entities, input: "Bob scans the perimeter.", compressed_snapshot: snapshot, simulation_log: history }],
    director_terse: ["director", { round: 2, terse: true }],
    interaction: ["interaction", { round: 1, entities, input: "Alice prepares to move.", compressed_snapshot: snapshot, simulation_log: history }],
    ghostwrite: ["ghostwrite", { round: 1, entities, input: "I steady my aim.", ghostwrite: true, compressed_snapshot: snapshot }],
    npc: ["npc", { round: 1, entities, input: "Merchant glances around.", npc, compressed_snapshot: snapshot }],
    narrator: [
      "narrator",
      { round: 1, entities, input: "The wind howls.", is_narrator: true, compressed_snapshot: snapshot, simulation_log: history },
    ],
    narrator_prologue: ["narrator", { round: 0, entities, is_prologue: true, scene_template: "PROLOGUE", compressed_snapshot: snapshot }],
    narrator_epilogue: [
      "narrator",
      {
        entities,
        simulation_log: history,
        is_epilogue: true,
        conclusion_status: "CONCLUDED",
        scene_template: "EPILOGUE",
        compressed_snapshot: snapshot,
      },
    ],
    continuum: ["continuum", { target_entity: entities.AI, target_key: "AI_CHARACTER", other_entities: entities, history }],
    enhancement: [
      "enhancement",
      {
        enhancer: "VOICE",
        label: "Personality",
        directive: "Expand vocal cadence",
        content: "Terse, dry.",
        field_id: "eternal.non_physical",
        layer_key: "ETERNAL",
        entity: entities.AI,
        entity_type: "character",
      },
    ],
    sorting: ["sorting", { entity_type: "character", options: { ingestion: true }, input_data: "Raw bio text" }],
    optics: [
      "optics",
      {
        tier: "solo_entity",
        subject_name: "Alice",
        prompt_context: "Standing on the catwalk in neon rain",
        is_selfie: false,
        ai: entities.AI,
        fractal: entities.FRACTAL,
        entity: entities.AI,
      },
    ],
  };
}

